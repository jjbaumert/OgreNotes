//! Symbol commands: what `\alpha`, `\leq`, `\sum`, `\sin`, … produce.

/// How a symbol command renders.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Sym {
    /// `<mi>`, italic when a single Latin/Greek letter (lowercase Greek).
    Ident(char),
    /// `<mi mathvariant="normal">` (uppercase Greek).
    Upright(char),
    /// `<mo>`: binary operators, relations, arrows, punctuation.
    Op(char),
    /// A delimiter; `<mo stretchy="false">` unless sized by `\left`/`\big`.
    Delim(char),
    /// Big operator whose limits go above/below in display style (`\sum`).
    BigOp(char),
    /// Integral: limits stay as sub/superscripts unless `\limits`.
    Integral(char),
}

