/// A delimiter written after `\left`, `\right`, `\big`, …: its character,
/// or `None` for the empty delimiter `.`.
pub(crate) fn delimiter_char(c: char) -> Option<Option<char>> {
    Some(match c {
        '.' => None,
        '(' | ')' | '[' | ']' | '|' | '/' => Some(c),
        '<' => Some('⟨'),
        '>' => Some('⟩'),
        _ => return None,
    })
}

pub(crate) fn delimiter_command(name: &str) -> Option<char> {
    Some(match name {
        "{" | "lbrace" => '{',
        "}" | "rbrace" => '}',
        "|" | "Vert" | "lVert" | "rVert" => '‖',
        _ => match symbol(name) {
            Some(Sym::Delim(c)) => c,
            _ => return None,
        },
    })
}

/// The negated form of a relation for `\not`: a precomposed character
/// when Unicode has one, else the relation followed by U+0338.
pub(crate) fn negate(c: char) -> String {
    let composed = match c {
        '=' => '≠',
        '<' => '≮',
        '>' => '≯',
        '≤' => '≰',
        '≥' => '≱',
        '∈' => '∉',
        '∋' => '∌',
        '⊂' => '⊄',
        '⊃' => '⊅',
        '⊆' => '⊈',
        '⊇' => '⊉',
        '≡' => '≢',
        '∼' => '≁',
        '≈' => '≉',
        '≃' => '≄',
        '≅' => '≇',
        '∣' => '∤',
        '∥' => '∦',
        '→' => '↛',
        '←' => '↚',
        _ => return format!("{c}\u{338}"),
    };
    composed.to_string()
}
